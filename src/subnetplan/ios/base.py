"""Settings every device gets: identity, local login, SSH-only remote access."""

from __future__ import annotations

from subnetplan.model import Network

# Secrets are never generated. The placeholder is easy to search for and
# obviously wrong, which is safer than a default that looks real.
PLACEHOLDER = "CHANGE-ME"


def header(hostname: str, network: Network) -> list[str]:
    return [
        "!",
        f"! {hostname}",
        f'! Generated by subnetplan for network "{network.name}".',
        f"! Replace every {PLACEHOLDER} before using this configuration.",
    ]


def identity(hostname: str, network: Network) -> list[str]:
    return [
        "service password-encryption",
        # Without this, a mistyped command makes the device try to resolve
        # it as a host name and hang for several seconds.
        "no ip domain-lookup",
        f"hostname {hostname}",
        f"ip domain-name {network.domain}",
        f"enable secret {PLACEHOLDER}",
        f"username admin privilege 15 secret {PLACEHOLDER}",
    ]


def access(vty_last: int) -> list[str]:
    """Console and remote access. `vty_last` is 4 on routers, 15 on switches."""
    return [
        "banner motd #Authorized access only. Activity is logged.#",
        "!",
        "line console 0",
        " login local",
        " logging synchronous",
        " exec-timeout 10 0",
        f"line vty 0 {vty_last}",
        " login local",
        # Telnet sends passwords in clear text.
        " transport input ssh",
        " exec-timeout 10 0",
        "!",
        "ip ssh version 2",
    ]
